def test_action_window_brackets_airborne_portion(wind5_log):
    """Window starts ~1 s before first sample with alt > 0.2 m and ends
    ~1 s after the last such sample."""
    t0, t1 = find_action_window(wind5_log.states)
    assert t0 is not None and t1 is not None
    # Drone airborne ~58-78 s in this log; tolerate generous bounds.
    assert 50.0 < t0 < 65.0, t0
    assert 70.0 < t1 < 85.0, t1
    assert t1 > t0


def test_action_window_none_when_never_airborne():
    states = [
        {"t": float(i), "pos_ned": [0, 0, 0], "vel_ned": [0, 0, 0]}
        for i in range(5)
    ]
    t0, t1 = find_action_window(states)
    assert t0 is None and t1 is None


def test_zoom_plot_written_alongside_full_plot(tmp_path):
    """Every airborne run produces matching plots in plots/full/ and
    plots/zoom/. Logs where the drone never reached >0.2 m altitude (e.g.
    aborted takeoffs) get a full plot but no zoom -- find_action_window
    returns None for those. So zoom is a SUBSET of full, not necessarily
    equal.
    """
    rc = main([str(LOGS), "--out", str(tmp_path), "--require-event"])
    assert rc == 0
    full = sorted((tmp_path / "plots" / "full").glob("*.png"))
    zoom = sorted((tmp_path / "plots" / "zoom").glob("*.png"))
    # At least 5 of each (the original named-profile runs).
    assert len(full) >= 5, full
    assert len(zoom) >= 5, zoom
    # Every zoom plot must have a matching full plot.
    full_names = {p.name for p in full}
    zoom_names = {p.name for p in zoom}
    assert zoom_names.issubset(full_names), (full_names, zoom_names)


def test_require_event_filters_to_official_runs(tmp_path):
    """--require-event includes only logs with capstone_disturbance_active.

    Excludes the May-2 pre-bridge logs and aborted boots. Every profile is
    graded against the calm gates now -- with hardcoded PIDs, every profile
    fails (calm fails on ~9 cm north drift, disturbance profiles fail by
    larger margins). RL's target is to bring all profiles to PASS.
    """
    rc = main([str(LOGS), "--out", str(tmp_path), "--no-plots", "--require-event"])
    assert rc == 0
    with (tmp_path / "baseline.csv").open() as f:
        rows = list(csv.DictReader(f))
    profiles = set(r["profile"] for r in rows)
    # All the named profiles we've run so far should be present.
    expected_subset = {"calm", "mass+10", "wind2", "wind5", "imu_noise"}
    assert expected_subset.issubset(profiles), profiles
    # Every profile fails the calm gate under hardcoded PIDs -- that's the
    # whole point of using uniform gates.
    failed = [r["profile"] for r in rows if r["passed"] == "0"]
    assert len(failed) == len(rows), \
        f"some profiles unexpectedly pass calm gate: {[r['profile'] for r in rows if r['passed'] == '1']}"
