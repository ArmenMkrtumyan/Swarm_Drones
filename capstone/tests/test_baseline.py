def test_extract_series_lengths_match(wind5_log):
    s = extract_series(wind5_log)
    n = len(s["t"])
    assert n == len(s["alt"]) == len(s["x"]) == len(s["y"])
    assert n == len(s["roll"]) == len(s["pitch"]) == len(s["yaw"])
    assert n == len(s["gyro_mag"])
    # wind5 log was produced after the bridge edit that adds wind_world.
    assert len(s["wind_mag"]) == n


def test_csv_row_has_all_fields(wind5_log):
    m = compute_metrics(wind5_log, "wind5")
    row = metrics_to_csv_row(m)
    expected = {
        "log_path", "profile", "duration_s", "n_state_samples",
        "window_t0", "window_t1", "window_duration_s",
        "alt_mean_m", "alt_std_m", "xy_std_m", "xy_excursion_max_m",
        "gyro_rms", "gyro_peak", "roll_std", "pitch_std",
        "crashed", "passed", "failures",
    }
    assert expected.issubset(row.keys())
    assert row["profile"] == "wind5"
    # Under uniform calm gates, wind5 fails -- 5 m/s wind pushes the drone
    # past the 5 cm position bound and the 3 deg tilt bound.
    assert row["passed"] == 0


def test_main_writes_baseline_artifacts(tmp_path):
    """End-to-end: --no-plots avoids matplotlib so the test stays fast.

    README.md is intentionally NOT generated by the tool -- the user
    hand-maintains it so their edits aren't overwritten on each run.
    """
    rc = main([str(LOGS), "--out", str(tmp_path), "--no-plots"])
    assert rc == 0
    assert (tmp_path / "baseline.csv").exists()
    assert (tmp_path / "baseline.json").exists()
    assert (tmp_path / "summary.txt").exists()
    assert not (tmp_path / "README.md").exists(), \
        "README.md should not be auto-generated -- it overwrites user edits"

    # CSV: every profile we ran must be present.
    with (tmp_path / "baseline.csv").open() as f:
        rows = list(csv.DictReader(f))
    profiles = {r["profile"] for r in rows}
    assert {"calm", "mass+10", "wind2", "wind5", "imu_noise"}.issubset(profiles), profiles


